package snmp

import (
	"fmt"
	"strings"

	"github.com/Netsession-LAN/Netsession-Relay/internal/notify"
)

// MIB renders NETSESSION-RELAY-MIB (SMIv2).
func MIB() string {
	var m mibText
	m.header()
	objects := m.scalars()
	objects = append(objects, m.tables()...)
	notifyObjs := m.notifyObjects()
	notes := m.notifications()
	m.conformance(append(objects, notifyObjs...), notes)
	return m.b.String()
}

// mibText collects the lines of the MIB file.
type mibText struct{ b strings.Builder }

// w writes one line.
func (m *mibText) w(format string, a ...any) { fmt.Fprintf(&m.b, format+"\n", a...) }

// mibParent names the object groups that scalars and notification objects hang below.
var mibParent = map[string]string{"1.1": "nsRelayStatus", "1.2": "nsRelayCounters", "1.6": "nsRelayEvent"}

// mibPlace splits a sub OID into its parent group's name and the last arc.
func mibPlace(sub string) (string, string) {
	i := strings.LastIndex(sub, ".")
	return mibParent[sub[:i]], sub[i+1:]
}

// lastArc is the last number of a sub OID.
func lastArc(sub string) string { return sub[strings.LastIndex(sub, ".")+1:] }

// objectType writes one OBJECT-TYPE definition below parent with the last arc n.
func (m *mibText) objectType(name, syntax, access, desc, parent, n string) {
	m.w("%s OBJECT-TYPE", name)
	m.w("    SYNTAX      %s", syntax)
	m.w("    MAX-ACCESS  %s", access)
	m.w("    STATUS      current")
	m.w("    DESCRIPTION \"%s\"", desc)
	m.w("    ::= { %s %s }", parent, n)
	m.w("")
}

// header writes the module header, imports, identity and the fixed object identifiers.
func (m *mibText) header() {
	m.w("NETSESSION-RELAY-MIB DEFINITIONS ::= BEGIN")
	m.w("")
	m.w("-- Generated by `nsrelay snmp-mib` from internal/snmp/mib.go. Do not edit by hand.")
	m.w("-- Enterprise number %d is the number IANA reserved for examples in documentation (RFC 5612). It is not", notify.PEN)
	m.w("-- assigned to this project and never collides with a real vendor. With an enterprise number of your own:")
	m.w("-- change PEN in internal/notify/notify.go, then regenerate this file and the Zabbix SNMP template")
	m.w("-- (`nsrelay snmp-mib`, `nsrelay snmp-mib -zabbix`).")
	m.w("")
	m.w("IMPORTS")
	m.w("    MODULE-IDENTITY, OBJECT-TYPE, NOTIFICATION-TYPE, enterprises,")
	m.w("    Integer32, Unsigned32, Gauge32, Counter64, TimeTicks FROM SNMPv2-SMI")
	m.w("    DisplayString, TruthValue FROM SNMPv2-TC")
	m.w("    MODULE-COMPLIANCE, OBJECT-GROUP, NOTIFICATION-GROUP FROM SNMPv2-CONF;")
	m.w("")
	m.w("nsRelayMIB MODULE-IDENTITY")
	m.w("    LAST-UPDATED \"202611160000Z\"")
	m.w("    ORGANIZATION \"Netsession e.V.\"")
	m.w("    CONTACT-INFO \"https://github.com/Netsession-LAN/Netsession-Relay\"")
	m.w("    DESCRIPTION  \"Netsession Relay: UDP broadcast and multicast relay for LAN game discovery.\"")
	m.w("    REVISION     \"202611160000Z\"")
	m.w("    DESCRIPTION  \"First version.\"")
	m.w("    ::= { netsessionProducts 1 }")
	m.w("")
	m.w("netsession         OBJECT IDENTIFIER ::= { enterprises %d }", notify.PEN)
	m.w("netsessionProducts OBJECT IDENTIFIER ::= { netsession 1 }")
	m.w("")
	m.w("nsRelayNotifications OBJECT IDENTIFIER ::= { nsRelayMIB 0 }")
	m.w("nsRelayObjects       OBJECT IDENTIFIER ::= { nsRelayMIB 1 }")
	m.w("nsRelayStatus        OBJECT IDENTIFIER ::= { nsRelayObjects 1 }")
	m.w("nsRelayCounters      OBJECT IDENTIFIER ::= { nsRelayObjects 2 }")
	m.w("nsRelayEvent         OBJECT IDENTIFIER ::= { nsRelayObjects 6 }")
	m.w("nsRelayConformance   OBJECT IDENTIFIER ::= { nsRelayMIB 2 }")
	m.w("")
}

// scalars writes the scalar objects and returns their names.
func (m *mibText) scalars() []string {
	var names []string
	for _, s := range Scalars {
		p, n := mibPlace(s.Sub)
		m.objectType(s.Name, s.Syntax.MIB, "read-only", s.Desc, p, n)
		names = append(names, s.Name)
	}
	return names
}

// tables writes every table and returns the names of the readable columns.
func (m *mibText) tables() []string {
	var names []string
	for _, t := range Tables {
		names = append(names, m.table(t)...)
	}
	return names
}

// table writes one table with its entry, row sequence and columns and returns the names of its readable
// columns.
func (m *mibText) table(t Table) []string {
	entryType := strings.ToUpper(t.Entry[:1]) + t.Entry[1:]
	m.objectType(t.Name, "SEQUENCE OF "+entryType, "not-accessible", t.Desc, "nsRelayObjects", lastArc(t.Sub))
	m.w("%s OBJECT-TYPE", t.Entry)
	m.w("    SYNTAX      %s", entryType)
	m.w("    MAX-ACCESS  not-accessible")
	m.w("    STATUS      current")
	m.w("    DESCRIPTION \"One row.\"")
	m.w("    INDEX       { %s }", t.Index.Name)
	m.w("    ::= { %s 1 }", t.Name)
	m.w("")
	cols := append([]Column{t.Index}, t.Columns...)
	m.sequence(entryType, cols)
	var names []string
	for _, c := range cols {
		access := "read-only"
		if c.Get == nil {
			access = "not-accessible"
		}
		m.objectType(c.Name, c.Syntax.MIB, access, c.Desc, t.Entry, fmt.Sprint(c.Sub))
		if c.Get != nil {
			names = append(names, c.Name)
		}
	}
	return names
}

// sequence writes the SEQUENCE type of a table entry.
func (m *mibText) sequence(entryType string, cols []Column) {
	m.w("%s ::= SEQUENCE {", entryType)
	for i, c := range cols {
		sep := ","
		if i == len(cols)-1 {
			sep = ""
		}
		m.w("    %s %s%s", c.Name, sequenceType(c.Syntax.MIB), sep)
	}
	m.w("}")
	m.w("")
}

// sequenceType is the bare type of a SYNTAX clause as a SEQUENCE lists it: without a range or size, and every
// enumeration as plain INTEGER.
func sequenceType(syntax string) string {
	if strings.HasPrefix(syntax, "INTEGER") {
		return "INTEGER"
	}
	if j := strings.IndexAny(syntax, " ("); j > 0 {
		return syntax[:j]
	}
	return syntax
}

// notifyObjects writes the objects that are only sent with notifications and returns their names.
func (m *mibText) notifyObjects() []string {
	var names []string
	for _, o := range NotifyObjects {
		p, n := mibPlace(o.Sub)
		m.objectType(o.Name, "DisplayString", "accessible-for-notify", o.Desc, p, n)
		names = append(names, o.Name)
	}
	return names
}

// notifications writes the NOTIFICATION-TYPEs and returns their names.
func (m *mibText) notifications() []string {
	var names []string
	for _, n := range Notifications {
		m.w("%s NOTIFICATION-TYPE", n.Name)
		m.w("    OBJECTS     { %s }", strings.Join(n.Objects, ", "))
		m.w("    STATUS      current")
		m.w("    DESCRIPTION \"%s\"", n.Desc)
		m.w("    ::= { nsRelayNotifications %s }", lastArc(n.Sub))
		m.w("")
		names = append(names, n.Name)
	}
	return names
}

// conformance writes the object and notification groups, the compliance statement and the module end.
func (m *mibText) conformance(objects, notes []string) {
	m.w("nsRelayGroups      OBJECT IDENTIFIER ::= { nsRelayConformance 1 }")
	m.w("nsRelayCompliances OBJECT IDENTIFIER ::= { nsRelayConformance 2 }")
	m.w("")
	m.w("nsRelayObjectGroup OBJECT-GROUP")
	m.w("    OBJECTS     { %s }", strings.Join(objects, ",\n                  "))
	m.w("    STATUS      current")
	m.w("    DESCRIPTION \"All objects.\"")
	m.w("    ::= { nsRelayGroups 1 }")
	m.w("")
	m.w("nsRelayNotificationGroup NOTIFICATION-GROUP")
	m.w("    NOTIFICATIONS { %s }", strings.Join(notes, ", "))
	m.w("    STATUS      current")
	m.w("    DESCRIPTION \"All notifications.\"")
	m.w("    ::= { nsRelayGroups 2 }")
	m.w("")
	m.w("nsRelayCompliance MODULE-COMPLIANCE")
	m.w("    STATUS      current")
	m.w("    DESCRIPTION \"Everything is mandatory.\"")
	m.w("    MODULE      -- this module")
	m.w("    MANDATORY-GROUPS { nsRelayObjectGroup, nsRelayNotificationGroup }")
	m.w("    ::= { nsRelayCompliances 1 }")
	m.w("")
	m.w("END")
}
